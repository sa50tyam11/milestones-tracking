import 'package:flutter/foundation.dart';
import '../core/constants/enums.dart';

/// The final outcome of a completed assessment session.
///
/// This represents the results generated *after* scoring is applied to an
/// [AssessmentSession]. It is distinct from [AssessmentAnswer] (which holds
/// an individual question response) and [AssessmentSession] (which holds
/// the collection of all answers).
///
/// ## Current State (Phase 8B MVP)
/// Since full clinical numerical scoring rules are not yet defined, this
/// model serves as a safe container. It supports the critical milestone
/// referral rule and provides a pending status for numerical scores.
///
/// Later phases will add:
/// - Overall risk level / status (when defined)
/// - Domain-specific scores (when defined)
/// - Observations or recommendations (when defined)
@immutable
class AssessmentResult {
  const AssessmentResult({
    required this.module,
    required this.status,
    required this.childId,
    required this.sessionId,
    required this.ageGroup,
    required this.referralRequired,
    required this.scoredAt,
  });

  /// Hardcoded to 'milestone' to support future module integration
  final String module;

  /// E.g. 'completed_pending_clinical_interpretation'
  final String status;

  /// References [Child.id]
  final String childId;

  /// References [AssessmentSession.sessionId]
  final String sessionId;

  /// The child's age group at the time of the session
  final AgeGroup ageGroup;

  /// True if a critical milestone received a 'No' response
  final bool referralRequired;

  /// When this result was generated by the scoring engine
  final DateTime scoredAt;

  // ---------------------------------------------------------------------------
  // Serialisation
  // ---------------------------------------------------------------------------

  factory AssessmentResult.fromJson(Map<String, dynamic> json) =>
      AssessmentResult(
        module:           json['module'] as String,
        status:           json['status'] as String,
        childId:          json['childId'] as String,
        sessionId:        json['sessionId'] as String,
        ageGroup:         AgeGroup.fromJson(json['ageGroup'] as String),
        referralRequired: json['referralRequired'] as bool,
        scoredAt:         DateTime.parse(json['scoredAt'] as String),
      );

  Map<String, dynamic> toJson() => {
        'module':           module,
        'status':           status,
        'childId':          childId,
        'sessionId':        sessionId,
        'ageGroup':         ageGroup.name,
        'referralRequired': referralRequired,
        'scoredAt':         scoredAt.toIso8601String(),
      };

  // ---------------------------------------------------------------------------
  // Equality and identity
  // ---------------------------------------------------------------------------

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is AssessmentResult &&
          other.childId == childId &&
          other.sessionId == sessionId;

  @override
  int get hashCode => childId.hashCode ^ sessionId.hashCode;

  @override
  String toString() =>
      'AssessmentResult(sessionId: $sessionId, childId: $childId, status: $status, referralRequired: $referralRequired)';
}
