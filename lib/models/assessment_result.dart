import 'package:flutter/foundation.dart';

/// The final outcome of a completed assessment session.
///
/// This represents the results generated *after* scoring is applied to an
/// [AssessmentSession]. It is distinct from [AssessmentAnswer] (which holds
/// an individual question response) and [AssessmentSession] (which holds
/// the collection of all answers).
///
/// ## Current State (Phase 4 MVP)
/// Since the clinical scoring engine (Phase 8) is not yet implemented, this
/// model serves as a minimal immutable shell establishing the data boundary.
/// 
/// Later phases will add:
/// - Overall risk level / status
/// - Domain-specific scores
/// - Observations or recommendations
@immutable
class AssessmentResult {
  const AssessmentResult({
    required this.childId,
    required this.sessionId,
    required this.scoredAt,
  });

  /// References [Child.id]
  final String childId;

  /// References [AssessmentSession.sessionId]
  final String sessionId;

  /// When this result was generated by the scoring engine
  final DateTime scoredAt;

  // ---------------------------------------------------------------------------
  // Serialisation (Stub)
  // ---------------------------------------------------------------------------

  factory AssessmentResult.fromJson(Map<String, dynamic> json) =>
      AssessmentResult(
        childId:   json['childId'] as String,
        sessionId: json['sessionId'] as String,
        scoredAt:  DateTime.parse(json['scoredAt'] as String),
      );

  Map<String, dynamic> toJson() => {
        'childId':   childId,
        'sessionId': sessionId,
        'scoredAt':  scoredAt.toIso8601String(),
      };

  // ---------------------------------------------------------------------------
  // Equality and identity
  // ---------------------------------------------------------------------------

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is AssessmentResult &&
          other.childId == childId &&
          other.sessionId == sessionId;

  @override
  int get hashCode => childId.hashCode ^ sessionId.hashCode;

  @override
  String toString() =>
      'AssessmentResult(sessionId: $sessionId, childId: $childId)';
}
